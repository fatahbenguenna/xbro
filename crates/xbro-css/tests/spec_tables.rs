//! Spec tables checked against browser behaviour: media query evaluation,
//! color parsing, and selector validity / specificity.

use xbro_css::*;

#[test]
fn media_queries_evaluate_like_browsers() {
    // Default context: 1024x768 screen, 1dppx, light scheme.
    let ctx = MediaContext::default();
    let table = [
        ("(width > 1023.5px)", true),
        ("(1024px = width)", true),
        ("(width < 0)", false),
        ("(min-width: -100px)", true),
        ("(max-width: 0)", false),
        ("(aspect-ratio > 1)", true),
        ("(min-aspect-ratio: 1.5)", false),
        ("(min-aspect-ratio: 4 / 3)", true),
        ("(device-aspect-ratio: 4/3)", true),
        ("(aspect-ratio: 1024/768)", true),
        ("(max-aspect-ratio: 1/1)", false),
        ("(resolution: 96dpi)", true),
        ("(min-resolution: 2x)", false),
        ("(min-resolution: 0.5dppx)", true),
        ("(resolution > 1x)", false),
        ("(prefers-color-scheme: DARK)", false),
        ("screen and (orientation: landscape)", true),
        ("(orientation: portrait)", false),
        ("(max-width: 50em)", false),
        ("(width >= 64em)", true),
        ("(width > 64em)", false),
        ("(width: calc(1024px))", false),
        ("(hover: hover) and (pointer: fine)", true),
        ("(any-hover: none)", false),
        ("print and (min-width: 0)", false),
        ("not print", true),
        ("not screen", false),
        ("not all", false),
        ("ALL", true),
        ("speech", false),
        ("tv", false),
        ("not tv", true),
        ("only tv", false),
        ("handheld, screen", true),
        ("(color-index)", false),
        ("(min-color-index: 0)", true),
        ("(monochrome: 0)", true),
        ("(grid: 0)", true),
        ("(scan: interlace)", false),
        ("(-webkit-min-device-pixel-ratio: 0)", true),
        ("(min--moz-device-pixel-ratio: 1)", true),
        ("(dynamic-range: high)", false),
        ("(inverted-colors)", false),
        ("(forced-colors: none)", true),
        ("(prefers-contrast: no-preference)", true),
        ("(prefers-reduced-motion)", false),
        ("(display-mode: standalone)", false),
        ("(width >= 100px) and (width <= 2000px)", true),
        ("((width >= 100px) or (unknown)) and (color)", true),
        ("not ((width < 100px) or (height < 100px))", true),
        ("(width < 100px) or (height < 100px)", false),
        // `not` takes a single operand: mixing it with `and` is invalid.
        ("not (width < 100px) and (color)", false),
        ("screen and not (color)", false),
        ("screen and (not (color))", false),
        ("(100px < width <= 1024px)", true),
        ("(1024px < width < 2000px)", false),
        ("(2000px > width > 100px)", true),
        ("(width > 100px > 50px)", false),
        ("(min-width: 100px", true),
        ("screen and (min-width:100px)and (max-width:2000px)", true),
        ("(min-height: 768px)", true),
        ("(height: 768px)", true),
        ("(width: 1024px)", true),
        ("(min-width: 640px) and (max-width: 1023.98px)", false),
        // IE hacks are invalid.
        ("(min-width: 0\\0)", false),
        ("\\0screen", false),
        ("screen\\9", false),
        (
            "(min-width: 1px) and (max-width: 0px), print, screen and (color)",
            true,
        ),
        ("(width >= 100PX)", true),
        ("(WIDTH >= 100px)", true),
        ("(min-width: 100Px)", true),
    ];
    for (query, expected) in table {
        assert_eq!(
            MediaQueryList::parse_str(query).matches(&ctx),
            expected,
            "{query}"
        );
    }
}

type Rgba = (u8, u8, u8, u8);

#[test]
fn colors_parse_like_browsers() {
    let table: &[(&str, Option<Rgba>)] = &[
        ("rgb(255 0 0 / 50%)", Some((255, 0, 0, 128))),
        ("hsl(120 100% 25%)", Some((0, 128, 0, 255))),
        ("#0f08", Some((0, 255, 0, 136))),
        ("rgba(0,0,0,.5)", Some((0, 0, 0, 128))),
        ("rgb(100%, 50%, 0%)", Some((255, 128, 0, 255))),
        ("rgb(10%, 20, 30)", None),
        ("rgb(1 2 3 4)", None),
        ("rgb(1,2,3,)", None),
        ("rgb(1 2 3 /)", None),
        ("rgb(none 0 0)", Some((0, 0, 0, 255))),
        ("rgb(none, 0, 0)", None),
        ("hsl(0, 100%, 50%)", Some((255, 0, 0, 255))),
        ("hsl(0, 100, 50)", None),
        ("hsl(0 100 50)", Some((255, 0, 0, 255))),
        ("hsl(240deg 100% 50% / 0.25)", Some((0, 0, 255, 64))),
        ("hsl(0.5turn 100% 50%)", Some((0, 255, 255, 255))),
        ("hsl(3.14159rad 100% 50%)", Some((0, 255, 255, 255))),
        ("hsl(200grad 100% 50%)", Some((0, 255, 255, 255))),
        ("hsl(-120 100% 50%)", Some((0, 0, 255, 255))),
        ("hsl(480 100% 50%)", Some((0, 255, 0, 255))),
        ("hwb(0 0% 0%)", Some((255, 0, 0, 255))),
        ("hwb(0 50% 50%)", Some((128, 128, 128, 255))),
        ("hwb(0, 0%, 0%)", None),
        ("lab(100 0 0)", Some((255, 255, 255, 255))),
        ("lab(0 0 0)", Some((0, 0, 0, 255))),
        ("oklch(1 0 0)", Some((255, 255, 255, 255))),
        ("oklab(0.628 0.2249 0.1258)", Some((255, 0, 0, 255))),
        ("color(srgb 1 0.5 0)", Some((255, 128, 0, 255))),
        ("color(srgb-linear 1 0 0)", Some((255, 0, 0, 255))),
        ("color(display-p3 0 1 0)", Some((0, 255, 0, 255))),
        ("color(xyz 0.9505 1 1.089)", Some((255, 255, 255, 255))),
        ("color(foo 1 0 0)", None),
        ("color-mix(in srgb, red, blue)", Some((128, 0, 128, 255))),
        ("color-mix(in srgb, red 25%, blue)", Some((64, 0, 191, 255))),
        ("color-mix(in srgb, red 0%, blue 0%)", None),
        (
            "color-mix(in srgb, transparent, red)",
            Some((255, 0, 0, 128)),
        ),
        ("light-dark(red, blue)", Some((255, 0, 0, 255))),
        ("transparent", Some((0, 0, 0, 0))),
        ("currentcolor", None),
        ("Canvas", Some((255, 255, 255, 255))),
        ("REBECCAPURPLE", Some((102, 51, 153, 255))),
        ("#12345", None),
        ("#1234567", None),
        ("rgb(300, -5, 128.4)", Some((255, 0, 128, 255))),
        ("rgba(0 0 0 / 150%)", Some((0, 0, 0, 255))),
        ("rgb(0 0 0 / -1)", Some((0, 0, 0, 0))),
        ("rgb(calc(255) 0 0)", None),
        ("rgb( 1 , 2 , 3 )", Some((1, 2, 3, 255))),
        ("RGB(1,2,3)", Some((1, 2, 3, 255))),
        ("rgb(1 2 3/0.5)", Some((1, 2, 3, 128))),
        ("#ABCDEF", Some((0xab, 0xcd, 0xef, 255))),
        ("#abcdef80", Some((0xab, 0xcd, 0xef, 0x80))),
        ("red blue", None),
        ("", None),
    ];
    for (input, expected) in table {
        let got = Color::parse_str(input).map(|c| (c.r, c.g, c.b, c.a));
        let close = match (got, expected) {
            (Some(g), Some(e)) => [
                g.0.abs_diff(e.0),
                g.1.abs_diff(e.1),
                g.2.abs_diff(e.2),
                g.3.abs_diff(e.3),
            ]
            .iter()
            .all(|d| *d <= 1),
            (None, None) => true,
            _ => false,
        };
        assert!(close, "{input:?}: got {got:?}, expected {expected:?}");
    }
}

#[test]
fn selector_validity_and_specificity_like_browsers() {
    let valid: &[(&str, (u32, u32, u32))] = &[
        ("*", (0, 0, 0)),
        ("li", (0, 0, 1)),
        ("ul ol+li", (0, 0, 3)),
        ("#x:not(.a.b)", (1, 2, 0)),
        (":where(#a) p", (0, 0, 1)),
        (":is(#a, p) .b", (1, 1, 0)),
        ("a::before", (0, 0, 2)),
        ("a:before", (0, 0, 2)),
        ("a:hover::before", (0, 1, 2)),
        ("::before:hover", (0, 1, 1)),
        ("*|*", (0, 0, 0)),
        ("ns|a", (0, 0, 1)),
        ("|a", (0, 0, 1)),
        ("[a|=b]", (0, 1, 0)),
        ("[ns|a]", (0, 1, 0)),
        ("[*|a=b i]", (0, 1, 0)),
        (":nth-child(2n+1)", (0, 1, 0)),
        (":nth-child( -n + 3 )", (0, 1, 0)),
        (":nth-child(+5)", (0, 1, 0)),
        (":has(> a, + b)", (0, 0, 1)),
        (":not(a, .b)", (0, 1, 0)),
        ("a>b~c+d e", (0, 0, 5)),
        // Forgiving lists drop invalid and empty items.
        (":is()", (0, 0, 0)),
        (":is(::before, a)", (0, 0, 1)),
        (":where(:unknown, a)", (0, 0, 0)),
        (":where(,)", (0, 0, 0)),
        (":lang(en, \"fr\")", (0, 1, 0)),
        (":dir(rtl)", (0, 1, 0)),
        ("::-webkit-scrollbar", (0, 0, 1)),
        ("::-webkit-scrollbar:horizontal", (0, 0, 1)),
        ("::-moz-selection", (0, 0, 1)),
        (":-webkit-autofill", (0, 1, 0)),
        (":host", (0, 1, 0)),
        (":host(.a)", (0, 1, 0)),
        (":state(x)", (0, 1, 0)),
        ("a:focus-visible", (0, 1, 1)),
        (":-moz-focusring", (0, 1, 0)),
        ("::marker", (0, 0, 1)),
        ("::part(x)", (0, 0, 1)),
        ("::slotted(a)", (0, 0, 1)),
        (":matches(a, b)", (0, 0, 1)),
        (":-webkit-any(a, b)", (0, 0, 1)),
        ("a\\:b", (0, 0, 1)),
        (".\\31 a", (0, 1, 0)),
        ("#\\31 a", (1, 0, 0)),
        // A top-level `&` is `:scope`.
        ("& .a", (0, 2, 0)),
        ("A", (0, 0, 1)),
        (":ROOT", (0, 1, 0)),
        ("::BEFORE", (0, 0, 1)),
        (":NOT(A)", (0, 0, 1)),
        (":nth-child(n)", (0, 1, 0)),
        (":nth-of-type(even)", (0, 1, 0)),
        ("a:not(:has(b))", (0, 0, 2)),
    ];
    for (text, (a, b, c)) in valid {
        let list = parse_selector_list(text).unwrap_or_else(|| panic!("{text:?} rejected"));
        let specificity = list.iter().map(Selector::specificity).max();
        assert_eq!(specificity, Some(Specificity(*a, *b, *c)), "{text:?}");
    }
    let invalid = [
        "",
        ",",
        "a,",
        ",a",
        "a,,b",
        "> a",
        "a >",
        "a > > b",
        "#1",
        ".1",
        "a::before b",
        "a::before.x",
        "::before::after",
        ":unknown",
        "::unknown",
        "a:hover(",
        ":nth-child()",
        ":nth-child(- n)",
        ":nth-child(+ 5)",
        ":nth-child(2n of .a)",
        ":not()",
        ":has()",
        ":has(:has(a))",
        ":has(::before)",
        ":not(::before)",
        "a|",
        "[a=1]",
        "[a~ =b]",
        "[a=b c]",
        "[]",
        "[=b]",
        "&div",
        "a b(c)",
        "a!b",
        "a/**/b",
        ":-ms-input-placeholder",
        "::-ms-clear",
        "a{",
        ":lang()",
        ":dir()",
        "a::before:not(:hover)",
        "::before:first-child",
        "a::after::before",
        "a  ,  ,b",
        "::selection::before",
    ];
    for text in invalid {
        assert!(parse_selector_list(text).is_none(), "{text:?} accepted");
    }
}
