//! Keyboard focus: focusable elements and the focus indication painted on
//! top of the page (a focus ring, plus a caret in text fields).

use xbro_dom::{Document, NodeId};
use xbro_layout::{BoxKind, ControlKind, Edges, Fragment, LayoutBox, LayoutTree, Rect};
use xbro_paint::{BorderSideItem, DisplayItem, DisplayList};
use xbro_style::{BorderStyle, Color, StyleMap};

use crate::forms;

/// Focus ring color (#1a73e8) and width.
const RING_COLOR: Color = Color::rgb(0x1a, 0x73, 0xe8);
const RING_WIDTH: f32 = 2.0;

/// Recursion guard for box tree walks.
const MAX_DEPTH: usize = 2048;

/// Focusable in sequential navigation: links, enabled form controls,
/// `summary`, and elements with `tabindex >= 0` (`tabindex < 0` removes an
/// element from the sequence).
pub(crate) fn is_focusable(doc: &Document, node: NodeId) -> bool {
    let Some(el) = doc.element(node) else {
        return false;
    };
    if let Some(t) = el.attr("tabindex") {
        if let Ok(v) = t.trim().parse::<i64>() {
            return v >= 0 && !(is_control(&el.name) && forms::is_disabled(doc, node));
        }
    }
    match el.name.as_str() {
        "a" | "area" => el.has_attr("href"),
        "input" => forms::input_type(doc, node) != "hidden" && !forms::is_disabled(doc, node),
        "select" | "textarea" | "button" => !forms::is_disabled(doc, node),
        "summary" => true,
        _ => false,
    }
}

fn is_control(name: &str) -> bool {
    matches!(name, "input" | "select" | "textarea" | "button")
}

/// Focusable elements that are rendered, in tree order.
pub(crate) fn focusable_elements(doc: &Document, styles: &StyleMap) -> Vec<NodeId> {
    doc.descendants(doc.root())
        .filter(|&n| styles.get(n).is_some() && is_focusable(doc, n))
        .collect()
}

/// Boxes and inline fragments generated by `node`, with whether they are in
/// a `position: fixed` subtree (viewport coordinates).
struct Found<'a> {
    rects: Vec<(Rect, bool)>,
    control: Option<(&'a LayoutBox, bool)>,
}

fn collect<'a>(
    b: &'a LayoutBox,
    node: NodeId,
    in_fixed: bool,
    found: &mut Found<'a>,
    depth: usize,
) {
    if depth > MAX_DEPTH {
        return;
    }
    let in_fixed = in_fixed || b.is_fixed();
    if b.node == Some(node) && b.pseudo.is_none() {
        found.rects.push((b.border_box(), in_fixed));
        if matches!(b.kind, BoxKind::Control(_)) && found.control.is_none() {
            found.control = Some((b, in_fixed));
        }
        return;
    }
    for line in &b.lines {
        for f in &line.fragments {
            match f {
                Fragment::InlineBox(ib) if ib.node == node => {
                    if !ib.rect.is_empty() {
                        found.rects.push((ib.rect, in_fixed));
                    }
                }
                Fragment::Atomic(a) => collect(a, node, in_fixed, found, depth + 1),
                _ => {}
            }
        }
    }
    for c in &b.children {
        collect(c, node, in_fixed, found, depth + 1);
    }
}

fn ring(rect: Rect) -> DisplayItem {
    let side = BorderSideItem {
        width: RING_WIDTH,
        style: BorderStyle::Solid,
        color: RING_COLOR,
    };
    DisplayItem::Border {
        rect: rect.outset(Edges::all(RING_WIDTH)),
        sides: [side; 4],
        radii: [3.0; 4],
    }
}

/// Caret rectangle of a focused text control box.
fn caret(doc: &Document, b: &LayoutBox, node: NodeId) -> Option<DisplayItem> {
    let textarea = matches!(b.kind, BoxKind::Control(ControlKind::TextArea));
    if !textarea && !matches!(b.kind, BoxKind::Control(ControlKind::TextField)) {
        return None;
    }
    let value = if textarea {
        forms::textarea_value(doc, node)
    } else {
        doc.attr(node, "value").unwrap_or("").to_string()
    };
    let content = b.content;
    let font_size = if b.style.font_size.is_finite() && b.style.font_size > 0.0 {
        b.style.font_size
    } else {
        16.0
    };
    let last_text = b
        .lines
        .iter()
        .rev()
        .flat_map(|l| l.fragments.iter().rev())
        .find_map(|f| match f {
            Fragment::Text(t) => Some(t),
            _ => None,
        });
    let (x, y, h) = match last_text {
        Some(t) if !value.is_empty() => {
            if textarea && value.ends_with('\n') {
                (content.x, t.rect.bottom(), t.rect.height)
            } else {
                let width = t
                    .glyphs
                    .iter()
                    .map(|g| g.x + g.advance)
                    .fold(0.0f32, f32::max)
                    .max(if t.glyphs.is_empty() {
                        t.rect.width
                    } else {
                        0.0
                    });
                (t.rect.x + width, t.rect.y, t.rect.height)
            }
        }
        _ => {
            // Empty value (a placeholder may be shown): caret at the content start.
            let line = b.lines.first().map(|l| l.rect);
            let h = line
                .map(|r| r.height)
                .unwrap_or(font_size * 1.2)
                .min(content.height.max(font_size));
            let y = match line {
                Some(r) => r.y,
                None => content.y + ((content.height - h) / 2.0).max(0.0),
            };
            (content.x, y, h)
        }
    };
    let x = x.min(content.right()).max(content.x);
    let rect = Rect::new(x, y, 1.0, h.max(1.0));
    (rect.x.is_finite() && rect.y.is_finite() && rect.height.is_finite()).then(|| {
        let color = if b.style.color.is_transparent() {
            Color::BLACK
        } else {
            b.style.color
        };
        DisplayItem::Rect {
            rect,
            color,
            radii: [0.0; 4],
        }
    })
}

/// Appends the focus indication of `focus` to `list`.
pub(crate) fn decorate(list: &mut DisplayList, tree: &LayoutTree, doc: &Document, focus: NodeId) {
    let Some(root) = &tree.root else {
        return;
    };
    let mut found = Found {
        rects: Vec::new(),
        control: None,
    };
    collect(root, focus, false, &mut found, 0);
    if found.rects.is_empty() {
        if let Some(r) = tree.node_rect(focus) {
            found.rects.push((r, false));
        }
    }
    let push = |item: DisplayItem, fixed: bool, list: &mut DisplayList| {
        if fixed {
            list.items.push(DisplayItem::PushFixed);
            list.items.push(item);
            list.items.push(DisplayItem::PopFixed);
        } else {
            list.items.push(item);
        }
    };
    for (rect, fixed) in found.rects.iter().take(64) {
        if rect.x.is_finite()
            && rect.y.is_finite()
            && rect.width.is_finite()
            && rect.height.is_finite()
        {
            push(ring(*rect), *fixed, list);
        }
    }
    if let Some((b, fixed)) = found.control {
        if let Some(c) = caret(doc, b, focus) {
            push(c, fixed, list);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn focusability() {
        let doc = xbro_html::parse_document(
            "<a id=a href=#>x</a><a id=noref>y</a><input id=i><input id=h type=hidden>\
             <input id=d disabled><div id=t tabindex=0></div><div id=n tabindex=-1></div>\
             <a id=neg href=# tabindex=-1>z</a><details><summary id=s>s</summary></details>\
             <button id=b>b</button><select id=sel></select><textarea id=ta></textarea>",
        );
        let f = |id: &str| is_focusable(&doc, doc.get_element_by_id(id).unwrap());
        assert!(f("a") && f("i") && f("t") && f("s") && f("b") && f("sel") && f("ta"));
        assert!(!f("noref") && !f("h") && !f("d") && !f("n") && !f("neg"));
    }
}
