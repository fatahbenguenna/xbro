/// Recursion guard for box trees (the DOM depth is bounded at 256 by the
/// parser; anonymous boxes add a few levels).
pub(super) const MAX_DEPTH: usize = 1024;

/// Builds a display list (entry point of the public `build_display_list*` functions).
pub(super) fn build(
    tree: &LayoutTree,
    fonts: Option<&FontSystem>,
    images: &dyn ImageProvider,
) -> DisplayList {
    let Some(root) = &tree.root else {
        return DisplayList {
            items: Vec::new(),
            background: Color::WHITE,
        };
    };
    let mut builder = Builder {
        fonts,
        images,
        items: Vec::new(),
        metrics: HashMap::new(),
        root,
        body: find_body(root),
        canvas_from_body: false,
        subtree_ends: OnceCell::new(),
    };
    let background = builder.canvas(tree);
    builder.paint_stacking_context(root, 0);
    DisplayList {
        items: builder.items,
        background,
    }
}

/// The `<body>` box: the last in-flow child of the root generated by an
/// element (the layout tree carries no tag names; the parser puts all
/// content after `<head>` into `<body>`, and `<head>` only generates a box
/// when an author style displays it, before the body).
fn find_body(root: &LayoutBox) -> Option<&LayoutBox> {
    root.children
        .iter()
        .rev()
        .find(|c| c.node.is_some() && c.pseudo.is_none() && !c.style.is_out_of_flow())
}

/// `opacity` with NaN treated as opaque, clamped to 0..=1.
fn opacity_of(style: &ComputedStyle) -> f32 {
    if style.opacity.is_nan() {
        1.0
    } else {
        style.opacity.clamp(0.0, 1.0)
    }
}

/// True when the box creates a stacking context (for a child of a flex
/// container when `parent_flex`).
pub(super) fn creates_stacking_context(b: &LayoutBox, parent_flex: bool) -> bool {
    let s = &b.style;
    opacity_of(s) < 1.0
        || matches!(s.position, Position::Fixed | Position::Sticky)
        || (s.z_index.is_some() && (s.position.is_positioned() || parent_flex))
}

/// True when the box is painted in a positioned layer of its stacking
/// context instead of with the normal flow.
pub(super) fn is_layered(b: &LayoutBox, parent_flex: bool) -> bool {
    b.style.position.is_positioned() || creates_stacking_context(b, parent_flex)
}

/// Non-positioned float.
fn is_float(b: &LayoutBox) -> bool {
    b.style.float != Float::None && !b.style.position.is_out_of_flow()
}

pub(super) fn is_visible(style: &ComputedStyle) -> bool {
    style.visibility == Visibility::Visible
}

/// `z-index` used for ordering a stacking context among its siblings.
fn z_order(b: &LayoutBox, parent_flex: bool) -> i32 {
    if b.style.position.is_positioned() || parent_flex {
        b.style.z_index.unwrap_or(0)
    } else {
        0
    }
}

/// A clip in a stacking context's clip arena (a linked list towards the root).
#[derive(Copy, Clone, Debug)]
struct ClipNode {
    rect: Rect,
    radii: [f32; 4],
    parent: Option<usize>,
}

/// Document-order key of a box: the index of its node (node ids grow in
/// document order as the parser creates them) and a rank among the boxes
/// of that node (0 the element, 1 its `::before`, 2 its `::after` keyed by
/// the last node of the element's subtree, 3 an anonymous box).
pub(super) type DocOrder = (usize, u8);

/// A box painted in one of the positioned layers of a stacking context.
struct Entry<'t> {
    b: &'t LayoutBox,
    /// Clips (in the stacking context's arena) applying to this box.
    clip: Option<usize>,
    /// Real stacking context (else a positioned `z-index: auto` box).
    real: bool,
    z: i32,
    /// Position in the document, which orders the layers' boxes: layout
    /// moves absolutely positioned boxes (and positioned `::before`
    /// overlays) under their containing block, after its in-flow
    /// children, so the box tree order is not the document order.
    order: DocOrder,
}

/// Positioned layers of one stacking context.
#[derive(Default)]
struct Layers<'t> {
    negative: Vec<Entry<'t>>,
    zero: Vec<Entry<'t>>,
    positive: Vec<Entry<'t>>,
    clips: Vec<ClipNode>,
}

impl Layers<'_> {
    fn add_clip(&mut self, rect: Rect, radii: [f32; 4], parent: Option<usize>) -> usize {
        self.clips.push(ClipNode {
            rect,
            radii,
            parent,
        });
        self.clips.len() - 1
    }
}

/// Text decoration geometry for one fragment (tops of the lines, in CSS px).
struct DecorationGeometry {
    thickness: f32,
    underline: f32,
    overline: f32,
    line_through: f32,
}

pub(super) struct Builder<'a, 't> {
    fonts: Option<&'a FontSystem>,
    pub(super) images: &'a dyn ImageProvider,
    pub(super) items: Vec<DisplayItem>,
    metrics: HashMap<(FontId, u32), xbro_text::FontMetrics>,
    root: &'t LayoutBox,
    body: Option<&'t LayoutBox>,
    /// The body's background was propagated to the canvas (do not paint it again).
    canvas_from_body: bool,
    /// For each element generating boxes: the largest node index in their
    /// subtrees (the document position of a positioned `::after`), built
    /// on first use.
    subtree_ends: OnceCell<HashMap<usize, usize>>,
}

impl<'a, 't> Builder<'a, 't> {
    // ---------------------------------------------------------------
    // Canvas
    // ---------------------------------------------------------------

    /// Computes the canvas background color and emits the canvas background
    /// image, if any (CSS Backgrounds §2.11.2).
    fn canvas(&mut self, tree: &LayoutTree) -> Color {
        let root = self.root;
        let has_background = |s: &ComputedStyle| {
            !s.background_color.is_transparent() || s.background_image.is_some()
        };
        let source = if has_background(&root.style) {
            Some(&root.style)
        } else if let Some(body) = self.body.filter(|b| has_background(&b.style)) {
            self.canvas_from_body = true;
            Some(&body.style)
        } else {
            None
        };
        let Some(style) = source else {
            return Color::WHITE;
        };
        let style = style.clone();
        if let Some(BackgroundImage::Url(url)) = &style.background_image {
            let doc = Rect::new(
                0.0,
                0.0,
                sane_len(tree.document_size.width.max(tree.viewport.width)),
                sane_len(tree.document_size.height.max(tree.viewport.height)),
            );
            let clip = doc.union(&sane_rect(root.border_box()));
            self.background_url(url, root.padding_box(), clip, [0.0; 4], &style);
        } else if let Some(BackgroundImage::LinearGradient { angle_deg, stops }) =
            &style.background_image
        {
            let doc = Rect::new(
                0.0,
                0.0,
                sane_len(tree.document_size.width.max(tree.viewport.width)),
                sane_len(tree.document_size.height.max(tree.viewport.height)),
            );
            if !stops.is_empty() {
                self.items.push(DisplayItem::LinearGradient {
                    rect: doc.union(&sane_rect(root.border_box())),
                    angle_deg: sane(*angle_deg),
                    stops: stops.clone(),
                    radii: [0.0; 4],
                });
            }
        }
        over_white(style.background_color)
    }

    /// True when `b`'s background is painted as the canvas instead.
    fn background_is_canvas(&self, b: &LayoutBox) -> bool {
        std::ptr::eq(b, self.root)
            || (self.canvas_from_body && self.body.is_some_and(|body| std::ptr::eq(b, body)))
    }

    /// True when `b` clips its descendants. The root's `overflow` (and the
    /// body's, when propagated) applies to the viewport, not to the box.
    fn clips(&self, b: &LayoutBox) -> bool {
        let s = &b.style;
        if !(s.overflow_x.clips() || s.overflow_y.clips()) {
            return false;
        }
        if std::ptr::eq(b, self.root) {
            return false;
        }
        let root_style = &self.root.style;
        let root_visible = !(root_style.overflow_x.clips() || root_style.overflow_y.clips());
        !(root_visible && self.body.is_some_and(|body| std::ptr::eq(b, body)))
    }

    /// Clip rect and radii for the descendants of `b` (its padding box).
    fn clip_shape(b: &LayoutBox) -> (Rect, [f32; 4]) {
        let radii = resolve_radii(&b.style.border_radius, sane_rect(b.border_box()));
        (sane_rect(b.padding_box()), inner_radii(radii, b.border))
    }

    // ---------------------------------------------------------------
    // Push/pop helpers (empty pairs are elided)
    // ---------------------------------------------------------------

    pub(super) fn push_clip(&mut self, rect: Rect, radii: [f32; 4]) {
        self.items.push(DisplayItem::PushClip {
            rect: sane_rect(rect),
            radii,
        });
    }

    pub(super) fn pop_clip(&mut self) {
        if matches!(self.items.last(), Some(DisplayItem::PushClip { .. })) {
            self.items.pop();
        } else {
            self.items.push(DisplayItem::PopClip);
        }
    }

    /// Pushes `b`'s overflow clip, if it has one; returns whether it did.
    fn push_box_clip(&mut self, b: &LayoutBox) -> bool {
        if !self.clips(b) {
            return false;
        }
        let (rect, radii) = Self::clip_shape(b);
        self.push_clip(rect, radii);
        true
    }

    fn pop_box_clip(&mut self, pushed: bool) {
        if pushed {
            self.pop_clip();
        }
    }

    fn pop_paired(&mut self, open: fn(&DisplayItem) -> bool, close: DisplayItem) {
        if self.items.last().is_some_and(open) {
            self.items.pop();
        } else {
            self.items.push(close);
        }
    }

    // ---------------------------------------------------------------
    // Stacking contexts
    // ---------------------------------------------------------------

    /// Paints a box that creates a stacking context (or the root).
    fn paint_stacking_context(&mut self, b: &'t LayoutBox, depth: usize) {
        if depth > MAX_DEPTH {
            return;
        }
        let opacity = opacity_of(&b.style);
        if opacity <= 0.0 {
            return;
        }
        let fixed = b.is_fixed();
        if fixed {
            self.items.push(DisplayItem::PushFixed);
        }
        if opacity < 1.0 {
            self.items.push(DisplayItem::PushOpacity(opacity));
        }
        let visible = is_visible(&b.style);
        if visible {
            self.paint_box_decorations(b);
        }

        let mut layers = Layers::default();
        let own_clip = if self.clips(b) {
            let (rect, radii) = Self::clip_shape(b);
            Some(layers.add_clip(rect, radii, None))
        } else {
            None
        };
        let abs_clip = if b.style.position.is_positioned() {
            own_clip
        } else {
            None
        };
        self.collect(b, &mut layers, own_clip, abs_clip, depth);
        // Stable sorts: equal keys keep the box tree order.
        layers.negative.sort_by_key(|e| (e.z, e.order));
        layers.zero.sort_by_key(|e| e.order);
        layers.positive.sort_by_key(|e| (e.z, e.order));
        let Layers {
            negative,
            zero,
            positive,
            clips,
        } = layers;

        self.paint_entries(negative.iter(), &clips, depth);
        let pushed = self.push_box_clip(b);
        self.paint_flow(b, depth);
        self.pop_box_clip(pushed);
        self.paint_entries(zero.iter().chain(&positive), &clips, depth);
        if visible {
            self.paint_box_outline(b);
        }

        if opacity < 1.0 {
            self.pop_paired(
                |i| matches!(i, DisplayItem::PushOpacity(_)),
                DisplayItem::PopOpacity,
            );
        }
        if fixed {
            self.pop_paired(
                |i| matches!(i, DisplayItem::PushFixed),
                DisplayItem::PopFixed,
            );
        }
    }

    /// Finds the positioned descendants and child stacking contexts of a
    /// stacking context, recording the clips that apply to each: all
    /// enclosing clips for in-flow and relatively positioned boxes, those
    /// up to the containing block for absolutely positioned boxes, none for
    /// fixed boxes.
    fn collect(
        &self,
        b: &'t LayoutBox,
        layers: &mut Layers<'t>,
        clip: Option<usize>,
        abs_clip: Option<usize>,
        depth: usize,
    ) {
        if depth > MAX_DEPTH {
            return;
        }
        let parent_flex = b.kind == BoxKind::Flex;
        let atomics = b
            .lines
            .iter()
            .flat_map(|l| &l.fragments)
            .filter_map(|f| match f {
                Fragment::Atomic(a) => Some(a),
                _ => None,
            });
        for c in b.children.iter().chain(atomics) {
            let c_clip = match c.style.position {
                Position::Absolute => abs_clip,
                Position::Fixed => None,
                _ => clip,
            };
            if creates_stacking_context(c, parent_flex) {
                let z = z_order(c, parent_flex);
                let entry = Entry {
                    b: c,
                    clip: c_clip,
                    real: true,
                    z,
                    order: self.doc_order(c, b),
                };
                match z {
                    z if z < 0 => layers.negative.push(entry),
                    0 => layers.zero.push(entry),
                    _ => layers.positive.push(entry),
                }
                continue;
            }
            let positioned = c.style.position.is_positioned();
            if positioned {
                layers.zero.push(Entry {
                    b: c,
                    clip: c_clip,
                    real: false,
                    z: 0,
                    order: self.doc_order(c, b),
                });
            }
            let inner = if self.clips(c) {
                let (rect, radii) = Self::clip_shape(c);
                Some(layers.add_clip(rect, radii, c_clip))
            } else {
                c_clip
            };
            let inner_abs = if positioned { inner } else { abs_clip };
            self.collect(c, layers, inner, inner_abs, depth + 1);
        }
    }

    /// Document-order key of the layered box `c`, found under `parent` in
    /// the box tree (see [`DocOrder`]).
    fn doc_order(&self, c: &LayoutBox, parent: &LayoutBox) -> DocOrder {
        match (c.node, c.pseudo) {
            (Some(node), None) => (node.0, 0),
            (Some(node), Some(Pseudo::Before)) => (node.0, 1),
            (Some(node), Some(Pseudo::After)) => {
                let ends = self.subtree_ends.get_or_init(|| subtree_ends(self.root));
                let end = ends.get(&node.0).copied().unwrap_or(node.0);
                (end.max(node.0), 2)
            }
            (None, _) => (parent.node.map_or(0, |n| n.0), 3),
        }
    }

    /// Paints positioned-layer entries, each inside its clip chain.
    /// Consecutive entries share the clips their chains have in common
    /// (nothing else is painted between them), so many positioned boxes
    /// inside deeply nested clipping containers do not repeat the whole
    /// chain each.
    fn paint_entries<'e>(
        &mut self,
        entries: impl Iterator<Item = &'e Entry<'t>>,
        clips: &[ClipNode],
        depth: usize,
    ) where
        't: 'e,
    {
        // Clip arena indices currently pushed, outermost first.
        let mut open: Vec<usize> = Vec::new();
        for entry in entries {
            let mut chain = Vec::new();
            let mut next = entry.clip;
            while let Some(i) = next {
                let Some(node) = clips.get(i) else { break };
                chain.push(i);
                next = node.parent;
                if chain.len() > MAX_DEPTH {
                    break;
                }
            }
            chain.reverse();
            let common = open.iter().zip(&chain).take_while(|(a, b)| a == b).count();
            while open.len() > common {
                open.pop();
                self.pop_clip();
            }
            for &i in chain.get(common..).unwrap_or_default() {
                if let Some(node) = clips.get(i) {
                    self.push_clip(node.rect, node.radii);
                    open.push(i);
                }
            }
            if entry.real {
                self.paint_stacking_context(entry.b, depth + 1);
            } else {
                self.paint_atomic(entry.b, depth + 1);
            }
        }
        for _ in open {
            self.pop_clip();
        }
    }

    /// Paints a box atomically ("as if it created a stacking context"),
    /// leaving its positioned descendants to the enclosing stacking context.
    fn paint_atomic(&mut self, b: &'t LayoutBox, depth: usize) {
        if depth > MAX_DEPTH {
            return;
        }
        let visible = is_visible(&b.style);
        if visible {
            self.paint_box_decorations(b);
        }
        let pushed = self.push_box_clip(b);
        self.paint_flow(b, depth);
        self.pop_box_clip(pushed);
        if visible {
            self.paint_box_outline(b);
        }
    }

    /// Steps 3–5 for the content of `b` (its own background is already painted).
    fn paint_flow(&mut self, b: &'t LayoutBox, depth: usize) {
        self.walk_blocks(b, depth + 1);
        self.walk_floats(b, depth + 1);
        self.paint_inline_content(b, depth + 1);
        self.walk_inlines(b, depth + 1);
    }

    /// Step 3: backgrounds and borders of in-flow block-level descendants.
    fn walk_blocks(&mut self, b: &'t LayoutBox, depth: usize) {
        if depth > MAX_DEPTH || b.kind == BoxKind::Flex {
            return;
        }
        for c in &b.children {
            if is_layered(c, false) || is_float(c) {
                continue;
            }
            if is_visible(&c.style) {
                self.paint_box_decorations(c);
            }
            let pushed = self.push_box_clip(c);
            self.walk_blocks(c, depth + 1);
            self.pop_box_clip(pushed);
        }
    }

    /// Step 4: floats, each painted atomically.
    fn walk_floats(&mut self, b: &'t LayoutBox, depth: usize) {
        if depth > MAX_DEPTH || b.kind == BoxKind::Flex {
            return;
        }
        for c in &b.children {
            if is_layered(c, false) {
                continue;
            }
            if is_float(c) {
                self.paint_atomic(c, depth + 1);
                continue;
            }
            let pushed = self.push_box_clip(c);
            self.walk_floats(c, depth + 1);
            self.pop_box_clip(pushed);
        }
    }

    /// Step 5: inline content of in-flow descendants (flex items atomically).
    fn walk_inlines(&mut self, b: &'t LayoutBox, depth: usize) {
        if depth > MAX_DEPTH {
            return;
        }
        let flex = b.kind == BoxKind::Flex;
        for c in &b.children {
            if is_layered(c, flex) {
                continue;
            }
            if flex {
                self.paint_atomic(c, depth + 1);
                continue;
            }
            if is_float(c) {
                continue;
            }
            let pushed = self.push_box_clip(c);
            self.paint_inline_content(c, depth + 1);
            self.walk_inlines(c, depth + 1);
            self.pop_box_clip(pushed);
            if is_visible(&c.style) {
                self.paint_box_outline(c);
            }
        }
    }

    /// The inline-level content of `b` itself: list marker, replaced
    /// content or control decorations, and line boxes.
    fn paint_inline_content(&mut self, b: &'t LayoutBox, depth: usize) {
        let visible = is_visible(&b.style);
        if visible {
            if let Some(marker) = &b.marker {
                self.paint_marker(b, marker);
            }
        }
        match &b.kind {
            BoxKind::Image => {
                let rect = sane_rect(b.content);
                if visible && !rect.is_empty() {
                    let image = match b.node {
                        Some(node) => Some(DisplayItem::NodeImage { rect, node }),
                        // Node-less image boxes are `content: url()` images
                        // and inside `list-style-image` markers.
                        None => url_image_of(&b.style).map(|url| DisplayItem::UrlImage {
                            rect,
                            url: url.to_string(),
                        }),
                    };
                    if let Some(image) = image {
                        // Replaced content is clipped to the curve of the
                        // content edge (`border-radius` on `<img>`).
                        let radii = content_radii(b);
                        let rounded = radii.iter().any(|&r| r > 0.0);
                        if rounded {
                            self.push_clip(rect, radii);
                        }
                        self.items.push(image);
                        if rounded {
                            self.pop_clip();
                        }
                    }
                }
                self.paint_lines(&b.lines, depth);
            }
            BoxKind::Control(kind) => self.paint_control(b, kind, visible, depth),
            _ => self.paint_lines(&b.lines, depth),
        }
    }

    // ---------------------------------------------------------------
    // Lines and text
    // ---------------------------------------------------------------

    pub(super) fn paint_lines(&mut self, lines: &'t [LineBox], depth: usize) {
        let slices = inline_slices(lines);
        for (index, line) in lines.iter().enumerate() {
            self.paint_line(line, index, slices.as_ref(), depth);
        }
    }

    /// One line box. Inline elements with `opacity < 1` group the
    /// fragments they contain (those starting inside their fragment on
    /// this line, which precedes them) in an opacity group.
    fn paint_line(
        &mut self,
        line: &'t LineBox,
        index: usize,
        slices: Option<&Slices>,
        depth: usize,
    ) {
        let mut outlines: Vec<&InlineBoxFragment> = Vec::new();
        let mut groups: Vec<InlineGroup> = Vec::new();
        for (position, fragment) in line.fragments.iter().enumerate() {
            let start = fragment_start(fragment);
            while groups.last().is_some_and(|g| !starts_inside(start, g.end)) {
                self.close_inline_group(groups.pop());
            }
            let hidden = groups.last().is_some_and(|g| g.hides);
            if let Fragment::InlineBox(ib) = fragment {
                let opacity = opacity_of(&ib.style);
                if opacity < 1.0 {
                    let push = !hidden && opacity > 0.0;
                    if push {
                        self.items.push(DisplayItem::PushOpacity(opacity));
                    }
                    groups.push(InlineGroup {
                        end: sane_rect(ib.rect).right(),
                        pushed: push,
                        hides: hidden || opacity <= 0.0,
                    });
                }
            }
            if groups.last().is_some_and(|g| g.hides) {
                continue;
            }
            match fragment {
                Fragment::Text(t) => self.paint_text(t),
                Fragment::InlineBox(ib) => {
                    if is_visible(&ib.style) {
                        let (first, last) = slices.and_then(|m| m.get(&ib.node.0)).map_or(
                            (true, true),
                            |&(first, last)| {
                                (first == (index, position), last == (index, position))
                            },
                        );
                        self.paint_inline_box(ib, first, last);
                        if ib.style.outline_width > 0.0 {
                            outlines.push(ib);
                        }
                    }
                }
                Fragment::Atomic(a) => {
                    if !is_layered(a, false) {
                        self.paint_atomic(a, depth + 1);
                    }
                }
            }
        }
        while !groups.is_empty() {
            self.close_inline_group(groups.pop());
        }
        for ib in outlines {
            self.paint_outline(&ib.style, ib.rect, [0.0; 4]);
        }
    }

    fn close_inline_group(&mut self, group: Option<InlineGroup>) {
        if group.is_some_and(|g| g.pushed) {
            self.pop_paired(
                |i| matches!(i, DisplayItem::PushOpacity(_)),
                DisplayItem::PopOpacity,
            );
        }
    }

    /// Background and border of an inline element's fragment. Corners are
    /// only rounded at the element's start (`first`) and end (`last`):
    /// the fragment is a slice of one box (`box-decoration-break: slice`).
    fn paint_inline_box(&mut self, ib: &InlineBoxFragment, first: bool, last: bool) {
        let rect = sane_rect(ib.rect);
        let mut radii = resolve_radii(&ib.style.border_radius, rect);
        if !first {
            radii[0] = 0.0;
            radii[3] = 0.0;
        }
        if !last {
            radii[1] = 0.0;
            radii[2] = 0.0;
        }
        self.paint_background(&ib.style, rect, rect.inset(ib.border), radii);
        self.paint_border(&ib.style, rect, ib.border, radii);
    }

    /// Text fragment: underline/overline, glyphs, then line-through.
    fn paint_text(&mut self, t: &xbro_layout::TextFragment) {
        let style = &t.style;
        if !is_visible(style) || !(t.font_size.is_finite() && t.font_size > 0.0) {
            return;
        }
        let deco = style.decorations_in_effect;
        let deco_color = style.decoration_color;
        let geometry = (!deco.is_none() && !deco_color.is_transparent() && t.rect.width > 0.0)
            .then(|| self.decoration_geometry(t));
        let line = |y: f32, thickness: f32| DisplayItem::Rect {
            rect: Rect::new(sane(t.rect.x), sane(y), sane_len(t.rect.width), thickness),
            color: deco_color,
            radii: [0.0; 4],
        };
        if let Some(g) = &geometry {
            if deco.underline {
                self.items.push(line(g.underline, g.thickness));
            }
            if deco.overline {
                self.items.push(line(g.overline, g.thickness));
            }
        }
        let ink = !style.color.is_transparent()
            && !t.glyphs.is_empty()
            && !t.text.chars().all(char::is_whitespace);
        if ink {
            self.items.push(DisplayItem::Text(GlyphRun {
                font: t.font,
                font_size: t.font_size,
                origin: xbro_layout::Point::new(sane(t.rect.x), sane(t.baseline)),
                glyphs: t.glyphs.clone(),
                color: style.color,
            }));
        }
        if let Some(g) = &geometry {
            if deco.line_through {
                self.items.push(line(g.line_through, g.thickness));
            }
        }
    }

    fn decoration_geometry(&mut self, t: &xbro_layout::TextFragment) -> DecorationGeometry {
        let size = t.font_size;
        let baseline = sane(t.baseline);
        match self.fonts {
            Some(fonts) => {
                let m = *self
                    .metrics
                    .entry((t.font, size.to_bits()))
                    .or_insert_with(|| fonts.metrics(t.font, size));
                let thickness = sane_len(m.underline_thickness).max(1.0);
                DecorationGeometry {
                    thickness,
                    underline: baseline + sane(m.underline_offset),
                    overline: baseline - sane_len(m.ascent),
                    line_through: baseline - sane_len(m.x_height) / 2.0 - thickness / 2.0,
                }
            }
            None => {
                let thickness = (size / 14.0).max(1.0);
                let ascent = baseline - sane(t.rect.y);
                let ascent = if ascent > 0.0 { ascent } else { size * 0.8 };
                DecorationGeometry {
                    thickness,
                    underline: baseline + size * 0.1,
                    overline: baseline - ascent,
                    line_through: baseline - size * 0.25 - thickness / 2.0,
                }
            }
        }
    }

    // ---------------------------------------------------------------
    // Box decorations
    // ---------------------------------------------------------------

    /// Background and border of a box (step 1/3).
    fn paint_box_decorations(&mut self, b: &LayoutBox) {
        let border_box = sane_rect(b.border_box());
        let radii = resolve_radii(&b.style.border_radius, border_box);
        if !self.background_is_canvas(b) {
            self.paint_background(&b.style, border_box, sane_rect(b.padding_box()), radii);
        }
        self.paint_border(&b.style, border_box, b.border, radii);
    }

    /// Background color (border box), then image or gradient.
    pub(super) fn paint_background(
        &mut self,
        style: &ComputedStyle,
        border_box: Rect,
        padding_box: Rect,
        radii: [f32; 4],
    ) {
        if border_box.is_empty() {
            return;
        }
        if !style.background_color.is_transparent() {
            self.items.push(DisplayItem::Rect {
                rect: border_box,
                color: style.background_color,
                radii,
            });
        }
        match &style.background_image {
            Some(BackgroundImage::Url(url)) => {
                self.background_url(url, padding_box, border_box, radii, style);
            }
            Some(BackgroundImage::LinearGradient { angle_deg, stops }) if !stops.is_empty() => {
                self.items.push(DisplayItem::LinearGradient {
                    rect: border_box,
                    angle_deg: sane(*angle_deg),
                    stops: stops.clone(),
                    radii,
                });
            }
            _ => {}
        }
    }

    /// A `url()` background: resolved now when the image (or an explicit
    /// size) is known, deferred to raster time otherwise.
    fn background_url(
        &mut self,
        url: &str,
        area: Rect,
        clip: Rect,
        radii: [f32; 4],
        style: &ComputedStyle,
    ) {
        let clip = sane_rect(clip);
        if url.is_empty() || clip.is_empty() {
            return;
        }
        let rounded = radii.iter().any(|&r| r > 0.0);
        if rounded {
            self.push_clip(clip, radii);
        }
        let natural = match (self.images.url_image(url), style.background_size) {
            (Some(image), _) => Some(image.natural_size()),
            (None, BackgroundSize::Explicit(Some(_), Some(_))) => Some(Size::new(0.0, 0.0)),
            (None, _) => None,
        };
        match natural {
            Some(natural) => {
                if let Some((origin, tile)) = background_tile(
                    area,
                    natural,
                    style.background_size,
                    style.background_position,
                ) {
                    self.items.push(DisplayItem::BackgroundImage {
                        url: url.to_string(),
                        clip,
                        origin,
                        tile,
                        repeat: style.background_repeat,
                    });
                }
            }
            None => self.items.push(DisplayItem::DeferredBackgroundImage {
                url: url.to_string(),
                area: sane_rect(area),
                clip,
                size: style.background_size,
                position: style.background_position,
                repeat: style.background_repeat,
            }),
        }
        if rounded {
            self.pop_clip();
        }
    }

    /// Border item from used widths and computed styles/colors.
    pub(super) fn paint_border(
        &mut self,
        style: &ComputedStyle,
        border_box: Rect,
        widths: Edges,
        radii: [f32; 4],
    ) {
        let side = |w: f32, s: &xbro_style::BorderSide| BorderSideItem {
            width: sane_len(w),
            style: s.style,
            color: s.color,
        };
        let sides = [
            side(widths.top, &style.border.top),
            side(widths.right, &style.border.right),
            side(widths.bottom, &style.border.bottom),
            side(widths.left, &style.border.left),
        ];
        if sides.iter().any(BorderSideItem::is_visible) && !border_box.is_empty() {
            self.items.push(DisplayItem::Border {
                rect: border_box,
                sides,
                radii,
            });
        }
    }

    /// The outline of a box, following its rounded corners.
    fn paint_box_outline(&mut self, b: &LayoutBox) {
        if b.style.outline_width > 0.0 {
            let border_box = sane_rect(b.border_box());
            let radii = resolve_radii(&b.style.border_radius, border_box);
            self.paint_outline(&b.style, border_box, radii);
        }
    }

    /// Outline: a solid border `outline_width` wide outside the border box
    /// (whose corner radii are `radii`; the outline's corners are rounded
    /// concentrically).
    fn paint_outline(&mut self, style: &ComputedStyle, border_box: Rect, radii: [f32; 4]) {
        let width = sane_len(style.outline_width);
        if width <= 0.0 || style.outline_color.is_transparent() {
            return;
        }
        let side = BorderSideItem {
            width,
            style: BorderStyle::Solid,
            color: style.outline_color,
        };
        let rect = sane_rect(border_box).outset(Edges::all(width));
        let radii = clamp_radii(radii.map(|r| if r > 0.0 { r + width } else { 0.0 }), rect);
        self.items.push(DisplayItem::Border {
            rect,
            sides: [side; 4],
            radii,
        });
    }

    // ---------------------------------------------------------------
    // List markers
    // ---------------------------------------------------------------

    fn paint_marker(&mut self, b: &LayoutBox, marker: &ListMarker) {
        let rect = sane_rect(marker.rect);
        let color = marker.color;
        match &marker.content {
            MarkerContent::Disc | MarkerContent::Circle | MarkerContent::Square => {
                if color.is_transparent() {
                    return;
                }
                let size = sane_len(b.style.font_size);
                let d = rect.width.min(rect.height).min((size * 0.35).max(1.0));
                if d <= 0.0 {
                    return;
                }
                let bullet = Rect::new(
                    rect.x + (rect.width - d) / 2.0,
                    rect.y + (rect.height - d) / 2.0,
                    d,
                    d,
                );
                self.items.push(match marker.content {
                    MarkerContent::Square => DisplayItem::Rect {
                        rect: bullet,
                        color,
                        radii: [0.0; 4],
                    },
                    MarkerContent::Circle => {
                        let stroke = (d / 6.0).max(1.0).min(d / 2.0);
                        DisplayItem::Ellipse {
                            rect: bullet.inset(Edges::all(stroke / 2.0)),
                            color,
                            fill: false,
                            stroke_width: stroke,
                        }
                    }
                    _ => DisplayItem::Ellipse {
                        rect: bullet,
                        color,
                        fill: true,
                        stroke_width: 0.0,
                    },
                });
            }
            MarkerContent::Text(t) => {
                if color.is_transparent()
                    || t.glyphs.is_empty()
                    || !(t.font_size.is_finite() && t.font_size > 0.0)
                {
                    return;
                }
                self.items.push(DisplayItem::Text(GlyphRun {
                    font: t.font,
                    font_size: t.font_size,
                    origin: xbro_layout::Point::new(sane(t.rect.x), sane(t.baseline)),
                    glyphs: t.glyphs.clone(),
                    color,
                }));
            }
            MarkerContent::Image(url) => {
                if !rect.is_empty() && !url.is_empty() {
                    self.items.push(DisplayItem::UrlImage {
                        rect,
                        url: url.clone(),
                    });
                }
            }
        }
    }
}

/// Tolerance (CSS px) when deciding whether a fragment starts inside an
/// inline element's fragment.
const GROUP_EDGE_EPSILON: f32 = 0.01;

/// An inline element with `opacity < 1` whose fragments are being painted.
#[derive(Copy, Clone)]
struct InlineGroup {
    /// Right edge of the element's fragment on the line.
    end: f32,
    /// A `PushOpacity` was emitted (to close).
    pushed: bool,
    /// Its content is invisible (`opacity: 0`, itself or an enclosing group).
    hides: bool,
}

/// True when a fragment starting at `start` lies inside an inline
/// element's fragment ending at `end` (false for NaN).
fn starts_inside(start: f32, end: f32) -> bool {
    start < end - GROUP_EDGE_EPSILON
}

/// Left edge of a fragment (CSS px).
fn fragment_start(fragment: &Fragment) -> f32 {
    match fragment {
        Fragment::Text(t) => t.rect.x,
        Fragment::InlineBox(ib) => ib.rect.x,
        Fragment::Atomic(a) => a.border_box().x,
    }
}

/// First and last fragment (line index, fragment index) of each inline
/// element, by node.
type Slices = HashMap<usize, ((usize, usize), (usize, usize))>;

/// [`Slices`] of the inline elements of `lines`, or `None` when no inline
/// element has rounded corners (the only use of the information).
fn inline_slices(lines: &[LineBox]) -> Option<Slices> {
    let rounded = lines.iter().flat_map(|l| &l.fragments).any(|f| {
        matches!(f, Fragment::InlineBox(ib) if ib.style.border_radius.iter().any(|r| !r.is_zero()))
    });
    if !rounded {
        return None;
    }
    let mut slices = Slices::new();
    for (index, line) in lines.iter().enumerate() {
        for (position, fragment) in line.fragments.iter().enumerate() {
            if let Fragment::InlineBox(ib) = fragment {
                let at = (index, position);
                slices
                    .entry(ib.node.0)
                    .and_modify(|e| e.1 = at)
                    .or_insert((at, at));
            }
        }
    }
    Some(slices)
}

/// Corner radii of the content edge of `b` (its border-box radii shrunk
/// by the border and padding widths, circular approximation).
fn content_radii(b: &LayoutBox) -> [f32; 4] {
    let radii = resolve_radii(&b.style.border_radius, sane_rect(b.border_box()));
    let inset = Edges::new(
        sane_len(b.border.top) + sane_len(b.padding.top),
        sane_len(b.border.right) + sane_len(b.padding.right),
        sane_len(b.border.bottom) + sane_len(b.padding.bottom),
        sane_len(b.border.left) + sane_len(b.padding.left),
    );
    inner_radii(radii, inset)
}

/// For every element generating boxes, the largest node index found in
/// the subtrees of its (non-pseudo) boxes: text, inline boxes, atomic
/// inlines and child boxes. One pass over the tree.
fn subtree_ends(root: &LayoutBox) -> HashMap<usize, usize> {
    fn walk(b: &LayoutBox, ends: &mut HashMap<usize, usize>, depth: usize) -> usize {
        let mut max = b.node.map_or(0, |n| n.0);
        if depth > MAX_DEPTH {
            return max;
        }
        for c in &b.children {
            max = max.max(walk(c, ends, depth + 1));
        }
        for fragment in b.lines.iter().flat_map(|l| &l.fragments) {
            let end = match fragment {
                Fragment::Text(t) => t.node.0,
                Fragment::InlineBox(ib) => ib.node.0,
                Fragment::Atomic(a) => walk(a, ends, depth + 1),
            };
            max = max.max(end);
        }
        if let Some(ListMarker {
            content: MarkerContent::Text(t),
            ..
        }) = &b.marker
        {
            max = max.max(t.node.0);
        }
        if let (Some(node), None) = (b.node, b.pseudo) {
            let end = ends.entry(node.0).or_insert(0);
            *end = (*end).max(max);
        }
        max
    }
    let mut ends = HashMap::new();
    walk(root, &mut ends, 0);
    ends
}

/// URL of a node-less image box: the single `url()` item of its `content`
/// (`::before`/`::after` images), else its `list-style-image` (inside
/// list markers drawn as images). `None` when neither names a URL.
fn url_image_of(style: &ComputedStyle) -> Option<&str> {
    if let Content::Items(items) = &style.content {
        let url = items.iter().find_map(|item| match item {
            ContentItem::Image(url) => Some(url.as_str()),
            _ => None,
        });
        if let Some(url) = url.filter(|u| !u.is_empty()) {
            return Some(url);
        }
    }
    style.list_style_image.as_deref().filter(|u| !u.is_empty())
}

/// Composites a (possibly translucent) canvas color over white.
fn over_white(c: Color) -> Color {
    if c.a == 255 {
        return c;
    }
    let a = u32::from(c.a);
    let mix = |v: u8| ((u32::from(v) * a + 255 * (255 - a) + 127) / 255) as u8;
    Color::rgb(mix(c.r), mix(c.g), mix(c.b))
}

